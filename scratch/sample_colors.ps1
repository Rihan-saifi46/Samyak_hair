Add-Type -AssemblyName System.Drawing
$fullPath = [System.IO.Path]::GetFullPath("assets/samyak-hero-banner.jpg")
$bmp = [System.Drawing.Bitmap]::FromFile($fullPath)
$cTL = $bmp.GetPixel(5, 5)
$cTC = $bmp.GetPixel(512, 5)
$cTR = $bmp.GetPixel(1015, 5)
$cBL = $bmp.GetPixel(5, 675)
$cBC = $bmp.GetPixel(512, 675)
$cBR = $bmp.GetPixel(1015, 675)
Write-Output ("TopLeft: #{0:X2}{1:X2}{2:X2}" -f $cTL.R, $cTL.G, $cTL.B)
Write-Output ("TopCenter: #{0:X2}{1:X2}{2:X2}" -f $cTC.R, $cTC.G, $cTC.B)
Write-Output ("TopRight: #{0:X2}{1:X2}{2:X2}" -f $cTR.R, $cTR.G, $cTR.B)
Write-Output ("BottomLeft: #{0:X2}{1:X2}{2:X2}" -f $cBL.R, $cBL.G, $cBL.B)
Write-Output ("BottomCenter: #{0:X2}{1:X2}{2:X2}" -f $cBC.R, $cBC.G, $cBC.B)
Write-Output ("BottomRight: #{0:X2}{1:X2}{2:X2}" -f $cBR.R, $cBR.G, $cBR.B)
$bmp.Dispose()
